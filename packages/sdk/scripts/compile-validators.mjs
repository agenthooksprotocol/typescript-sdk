// Precompile the canonical schema validators into plain ES module code, so the
// SDK never generates code at run time (sandboxes refuse `new Function`).
// The output is sharded into modules of bounded size (hosts such as Claude Code
// mods refuse a module file over 1 MiB), cross-importing what they share.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";
import { Ajv2020, _ } from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { fullFormats } from "ajv-formats/dist/formats.js";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const output = join(root, "src/draft/validators");
// Bytes of generated source per shard, comfortably under a 1 MiB file limit.
const SHARD_BUDGET = 512 * 1024;
const HEADER = "// Generated by scripts/compile-validators.mjs. DO NOT EDIT.\n// @ts-nocheck\n";
const scratch = join(root, ".validators");

// The generator reads the TypeScript sources directly: they import nothing
// relative, so a transpile-only pass is exact.
async function load(relative) {
  const source = readFileSync(join(root, relative), "utf8");
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  });
  const file = join(scratch, relative.replaceAll("/", "_").replace(/\.ts$/, ".mjs"));
  writeFileSync(file, outputText);
  return import(pathToFileURL(file).href);
}

// Every format any registry used before precompilation.
const FORMATS = ["uri", "email", "date-time"];

mkdirSync(scratch, { recursive: true });
let files;
try {
  const { schemas } = await load("src/draft/schemas.ts");
  const { addCanonicalKeywords, canonicalSchema } = await load("src/canonical-schema.ts");
  const ajv = new Ajv2020({
    allErrors: true,
    strict: false,
    ownProperties: true,
    // Shared definitions compile once instead of being inlined per reference.
    inlineRefs: false,
    code: { source: true, esm: true, lines: false, formats: _`formats` },
  });
  for (const name of FORMATS) ajv.addFormat(name, fullFormats[name]);
  addCanonicalKeywords(ajv);
  for (const schema of schemas) ajv.addSchema(canonicalSchema(schema));

  // Each schema and each of its top-level definitions is addressable by URI.
  const ids = [];
  for (const schema of schemas) {
    ids.push(schema.$id);
    for (const name of Object.keys(schema.$defs ?? {}))
      ids.push(`${schema.$id}#/$defs/${encodeURIComponent(name)}`);
  }
  const exports = Object.fromEntries(ids.map((id, index) => [`v${index}`, id]));
  const body = [
    'import { fullFormats as formats } from "ajv-formats/dist/formats.js";',
    ...hoistHelpers(standaloneCode(ajv, exports)),
  ].join("\n");
  files = shard(body, ids);
} finally {
  rmSync(scratch, { recursive: true, force: true });
}

// Standalone output loads runtime helpers with inline `require` even in ESM
// mode; hoist each one to a static import with an explicit file extension.
function hoistHelpers(body) {
  const helpers = new Map();
  const rewritten = body.replace(
    /require\("((?:ajv|ajv-formats)\/dist\/[^"]+?)(?:\.js)?"\)(\.default)?/g,
    (_match, path, isDefault) => {
      const key = `${path}|${isDefault ? "default" : "module"}`;
      if (!helpers.has(key)) helpers.set(key, { name: `helper${helpers.size}`, path, isDefault });
      return helpers.get(key).name;
    },
  );
  if (/\brequire\(/.test(rewritten)) throw new Error("Unexpected require in standalone output");
  // The helpers are CommonJS: Node hands an ESM default import the whole
  // `module.exports`, a bundler its `default`; accept either.
  const imports = [...helpers.values()].flatMap(({ name, path, isDefault }) =>
    isDefault
      ? [`import * as ${name}Module from "${path}.js";`,
         `const ${name} = ${name}Module.default?.default ?? ${name}Module.default;`]
      : [`import * as ${name} from "${path}.js";`]);
  return [...imports, rewritten];
}

/** Split standalone output into shards of whole top-level statements. Each
 * shard exports what it declares and imports what it uses from the others;
 * function declarations are hoisted, so cyclic imports between shards are safe. */
function shard(body, ids) {
  const source = ts.createSourceFile("validators.js", body, ts.ScriptTarget.ES2022, true, ts.ScriptKind.JS);
  const imports = new Map(); // local name -> import declaration text
  const statements = [];
  const owner = new Map(); // top-level name -> shard index
  for (const statement of source.statements) {
    if (ts.isImportDeclaration(statement)) {
      const clause = statement.importClause;
      const names = [];
      if (clause?.name) names.push(clause.name.text);
      if (clause?.namedBindings && ts.isNamespaceImport(clause.namedBindings)) names.push(clause.namedBindings.name.text);
      if (clause?.namedBindings && ts.isNamedImports(clause.namedBindings))
        for (const element of clause.namedBindings.elements) names.push(element.name.text);
      for (const name of names) imports.set(name, statement.getText(source));
      continue;
    }
    if (ts.isExpressionStatement(statement) && ts.isStringLiteral(statement.expression)) continue; // "use strict"
    const declared = [];
    if (ts.isFunctionDeclaration(statement) && statement.name) declared.push(statement.name.text);
    if (ts.isVariableStatement(statement))
      for (const declaration of statement.declarationList.declarations)
        if (ts.isIdentifier(declaration.name)) declared.push(declaration.name.text);
    const used = new Set();
    const visit = (node) => {
      if (ts.isIdentifier(node)) used.add(node.text);
      ts.forEachChild(node, visit);
    };
    visit(statement);
    const text = statement.getText(source).replace(/^export\s+/, "");
    statements.push({ text, declared, used });
  }
  const shards = [];
  for (const statement of statements) {
    let current = shards.at(-1);
    if (!current || (current.size + statement.text.length > SHARD_BUDGET && current.statements.length)) {
      current = { statements: [], size: 0 };
      shards.push(current);
    }
    current.statements.push(statement);
    current.size += statement.text.length + 1;
    for (const name of statement.declared) owner.set(name, shards.length - 1);
  }
  const files = new Map();
  shards.forEach((part, index) => {
    const declared = new Set(part.statements.flatMap((statement) => statement.declared));
    const external = new Set();
    const siblings = new Map();
    for (const statement of part.statements)
      for (const name of statement.used) {
        if (declared.has(name)) continue;
        if (imports.has(name)) external.add(imports.get(name));
        else if (owner.has(name)) {
          const from = owner.get(name);
          if (!siblings.has(from)) siblings.set(from, new Set());
          siblings.get(from).add(name);
        }
      }
    files.set(`part-${index}.ts`, [
      HEADER,
      ...[...external].sort(),
      ...[...siblings].sort(([a], [b]) => a - b)
        .map(([from, names]) => `import { ${[...names].sort().join(", ")} } from "./part-${from}.js";`),
      ...part.statements.map((statement) => statement.text),
      `export { ${[...declared].join(", ")} };`,
      "",
    ].join("\n"));
  });
  const byShard = new Map();
  ids.forEach((_, index) => {
    const name = `v${index}`;
    const from = owner.get(name);
    if (!byShard.has(from)) byShard.set(from, []);
    byShard.get(from).push(name);
  });
  files.set("index.ts", [
    HEADER,
    ...[...byShard].sort(([a], [b]) => a - b)
      .map(([from, names]) => `import { ${names.join(", ")} } from "./part-${from}.js";`),
    "",
    "/** Precompiled canonical validators by schema URI (with `#/$defs/<name>`). */",
    "export const validators = {",
    ...ids.map((id, index) => `  ${JSON.stringify(id)}: v${index},`),
    "};",
    "",
  ].join("\n"));
  return files;
}

rmSync(output, { recursive: true, force: true });
mkdirSync(output, { recursive: true });
for (const [name, text] of files) writeFileSync(join(output, name), text);
